#!/usr/bin/env node
/*
 * third-party-notices.mjs — list the open-source code inside the Signer
 * ====================================================================
 *
 * Run from the `app` folder (after `npm ci`):
 *
 *     node tools/third-party-notices.mjs
 *
 * The Signer is GPL-3.0-or-later, but it's built from many smaller
 * open-source packages (MIT, ISC, BSD, Apache-2.0…). Their licences allow
 * this, on one condition: their copyright and licence text must travel with
 * the app. This script writes THIRD-PARTY-NOTICES.md at the top of the
 * project with every package installed for the app (not the "dev" tools;
 * Expo's own build tools are included, which is harmless),
 * its licence and the licence text it ships with, plus OpenSSL, which
 * react-native-quick-crypto builds into the app from outside npm.
 *
 * Re-run it before every release (RELEASING.md) and attach the file to the
 * GitHub release. It only reads files; nothing is downloaded.
 */

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const APP = fileURLToPath(new URL('..', import.meta.url));
const OUT = join(APP, '..', 'THIRD-PARTY-NOTICES.md');

const lock = JSON.parse(readFileSync(join(APP, 'package-lock.json'), 'utf8'));
const own = lock.packages[''];

/** The licence file a package ships with (LICENSE, LICENCE, COPYING, …), or null. */
function licenceText(dir) {
  if (!existsSync(dir)) return null;
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying|notice)(\.|-|$)/i.test(f));
  return file ? readFileSync(join(dir, file), 'utf8').trim() : null;
}

/** "MIT" | {type:"MIT"} | [{type}] → "MIT". */
function licenceName(pkg) {
  const l = pkg.license ?? pkg.licenses;
  if (!l) return 'UNKNOWN';
  if (typeof l === 'string') return l;
  if (Array.isArray(l)) return l.map((x) => x.type || x).join(' OR ');
  return l.type || 'UNKNOWN';
}

const entries = [];
for (const [path, info] of Object.entries(lock.packages)) {
  if (!path || info.dev || info.link) continue; // "" = the Signer itself; dev = build tools only
  const dir = join(APP, path);
  const name = path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length);
  let pkg = {};
  try {
    pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  } catch {
    // not installed on this computer (e.g. optional, other platform)
    if (info.optional) continue;
  }
  entries.push({
    name,
    version: info.version || pkg.version || '?',
    licence: info.license || licenceName(pkg),
    text: licenceText(dir),
  });
}
entries.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

// OpenSSL: built into react-native-quick-crypto's native library (Gradle
// package io.github.ronickg:openssl-static), so it isn't in package-lock.
const quickCryptoGradle = join(APP, 'node_modules/react-native-quick-crypto/android/build.gradle');
const opensslVersion = existsSync(quickCryptoGradle)
  ? (readFileSync(quickCryptoGradle, 'utf8').match(/openssl-static:([\w.-]+)/) || [])[1]
  : null;
const apache = readFileSync(join(APP, 'tools', 'licences', 'APACHE-2.0.txt'), 'utf8').trim();
entries.push({
  name: 'OpenSSL (via io.github.ronickg:openssl-static)',
  version: opensslVersion || '3.x',
  licence: 'Apache-2.0',
  text: `Copyright (c) 1998-2025 The OpenSSL Project Authors\nCopyright (c) 1995-1998 Eric A. Young, Tim J. Hudson\nAll rights reserved.\n\n${apache}`,
});

const unknown = entries.filter((e) => !e.text);
const lines = [
  '# Third-party notices',
  '',
  `KLV Signer ${own.version} is free software under the GNU General Public License,`,
  'version 3 or later (see LICENSE). It includes the open-source packages below,',
  'each under its own licence. Their copyright notices and licence texts follow.',
  '',
  'Generated by `app/tools/third-party-notices.mjs` from package-lock.json. It lists',
  "every package installed for the app, including some of Expo's build tools that",
  "never end up inside it (listing them does no harm). Packages without their own",
  'licence file are listed with the licence their package.json declares.',
  '',
  '| Package | Version | Licence |',
  '|---|---|---|',
  ...entries.map((e) => `| ${e.name} | ${e.version} | ${e.licence} |`),
  '',
  '---',
  '',
];
for (const e of entries) {
  lines.push(`## ${e.name} ${e.version} (${e.licence})`, '');
  lines.push(e.text ? '```text\n' + e.text.replace(/```/g, "'''") + '\n```' : `_No licence file shipped in the package; its package.json declares "${e.licence}"._`, '');
}
writeFileSync(OUT, `${lines.join('\n')}\n`);

const byLicence = {};
for (const e of entries) byLicence[e.licence] = (byLicence[e.licence] || 0) + 1;
console.log(`Wrote ${OUT}: ${entries.length} packages.`);
console.log('Licences:', Object.entries(byLicence).sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} ${n}`).join(', '));
if (unknown.length) console.log(`Without a licence file (declared licence listed instead): ${unknown.map((e) => e.name).join(', ')}`);
